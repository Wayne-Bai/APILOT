from werkzeug.security import generate_password_hash, check_password_hash

def pbkdf2_hex(password, salt, iterations=200000, key_length=24, hash_name='sha256'):
    """
    Like pbkdf2_bin, but returns a hex-encoded string.

    :param password: the password to derive the key from
    :param salt: the salt to use for the key derivation
    :param iterations: the number of iterations to use
    :param key_length: the length of the key to generate
    :param hash_name: the name of the hash function to use
    :return: the hex-encoded key
    """
    return generate_password_hash(password, salt=salt, method=f'pbkdf2:{hash_name}:{iterations}:{key_length}', length=key_length)

# Example usage:
password ='mysecretpassword'
salt = 'randomsaltvalue'
hashed_password = pbkdf2_hex(password, salt)

print(hashed_password)

# Verify the hashed password
is_valid = check_password_hash(hashed_password, password)
print(is_valid)  # This will print False, because the hashed_password is not the one generated by check_password_hash

is_valid = check_password_hash(pbkdf2_hex(password, salt), password)
print(is_valid)  # This will print False, because check_password_hash method in werkzeug generates password hash 
                 # in format like bcrypt,argon2,creating  not in simple pbkdf2:hash_name:iter:salt:hash

# to match we have to use generate_password_hash from werkzeug to hash password 
is_valid = check_password_hash(generate_password_hash(password, salt=salt, method='pbkdf2:sha256:200000'), password) 
print(is_valid)       # This will print True
