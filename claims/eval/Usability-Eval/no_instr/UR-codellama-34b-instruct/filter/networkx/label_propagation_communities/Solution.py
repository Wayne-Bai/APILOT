
import networkx as nx

# Create a graph
G = nx.Graph()

# Add nodes and edges to the graph
G.add_nodes_from(['A', 'B', 'C', 'D'])
G.add_edges_from([('A', 'B'), ('B', 'C'), ('C', 'D')])

# Define a function for label propagation
def label_propagate(G, node):
    # Initialize the label of each node to its degree
    labels = dict.fromkeys(G.nodes(), 0)
    labels[node] = 1
    
    # Propagate labels from the given node to all neighbors
    for neighbor in G.neighbors(node):
        labels[neighbor] = max(labels[neighbor], labels[node])
    
    return labels

# Apply label propagation to each node in the graph
for node in G.nodes():
    labels = label_propagate(G, node)

# Print the community sets generated by label propagation
print("Community sets:")
for key, value in labels.items():
    print(f"{key}: {value}")
