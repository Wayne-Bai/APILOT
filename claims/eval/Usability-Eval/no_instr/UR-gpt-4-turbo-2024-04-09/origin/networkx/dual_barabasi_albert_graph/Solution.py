import networkx as nx

def dual_barabasi_albert_graph(n, m1, m2, p, seed=None):
    """
    Generates a random graph using a dual Barabási–Albert preferential attachment model.
    
    Parameters:
        n (int): Number of nodes
        m1 (int): Number of edges to attach from a new node to existing nodes
        m2 (int): Number of edges to attach from existing nodes to the new node
        p (float): Probability of adding a triangle after adding a new edge
        seed (int, optional): Seed for the random number generator

    Returns:
        Graph (networkx.Graph): A graph with n nodes generated by the dual Barabási–Albert model
    """
    if m1 < 1 or m2 < 0:
        raise nx.NetworkXError("Barabási–Albert network must have m1 >= 1 and m2 >= 0")
    if m1 + m2 < 1:
        raise nx.NetworkXError("Barabási–Albert network must have m1 + m2 >= 1")
    if n < m1 + m2:
        raise nx.NetworkXError("Barabási–Albert network must have n >= m1 + m2")

    # Create a graph with m1 + m2 initial nodes
    G = nx.empty_graph(m1 + m2)

    # Target nodes for new edges
    targets = list(range(m1 + m2))
    source = m1 + m2
    while source < n:
        G.add_edges_from(zip([source] * m1, targets))  # Add m1 edges from new node to existing

        # Now add m2 edges from existing nodes to new node, sample with replacement
        if m2:
            new_targets = nx.random.choices(targets, k=m2, seed=seed)
            G.add_edges_from(zip(new_targets, [source] * m2))

        # Add node to the list
        targets.extend([source] * (m1 + m2))
        
        # Add one random triangle to increase clustering (done with probability p)
        if p > 0:
            if nx.random.random() < p:
                u = nx.random.choice(targets)
                v = nx.random.choice(list(G[u]))
                if G.has_edge(source, v) or source == v:
                    continue
                G.add_edge(source, v)
                
        source += 1

    return G

# Example use
graph = dual_barabasi_albert_graph(n=100, m1=2, m2=1, p=0.1, seed=42)
print(nx.info(graph))
