import numpy as np
from scipy.stats import rankdata
import matplotlib.pyplot as plt

# Function to perform Latin Hypercube Sampling (LHS)
def latin_hypercube_sampling(dimensions, max_value, num_samples):
    """
    Perform Latin Hypercube Sampling (LHS) to generate samples.

    Parameters:
    dimensions (int): Number of dimensions in the space.
    max_value (float): Maximum value in each dimension.
    num_samples (int): Number of samples to generate.

    Returns:
    samples (numpy array): Samples generated by LHS.
    """
    # Generate random samples within the range
    samples = np.random.rand(num_samples, dimensions)

    # Shift samples to the desired range
    samples = (max_value - 1) * samples + 1

    # Sort the samples based on their rank in each dimension
    samples_sorted = []
    for i in range(dimensions):
        samples_ranked = rankdata(samples[:, i])
        samples_sorted.append(np.interp(np.linspace(1, num_samples, num_samples), np.linspace(1, num_samples, num_samples), samples_ranked))

    # Select samples with the same rank in each dimension
    samples_selected = []
    for i in range(num_samples):
        sample = []
        for j in range(dimensions):
            rank_index = np.where(samples_sorted[j] == i + 1)[0][0]
            sample.append(samples[rank_index, j])
        samples_selected.append(sample)

    return np.array(samples_selected)

# Example usage:
dimensions = 2
max_value = 100
num_samples = 10

samples = latin_hypercube_sampling(dimensions, max_value, num_samples)

print("Generated Samples:")
print(samples)

# Plotting the samples for visualization
plt.scatter(samples[:, 0], samples[:, 1])
plt.title('Latin Hypercube Sampling')
plt.xlabel('Dimension 1')
plt.ylabel('Dimension 2')
plt.grid(True)
plt.show()

