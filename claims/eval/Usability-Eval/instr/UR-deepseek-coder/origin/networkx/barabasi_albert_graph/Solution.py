import networkx as nx
import random

def barabasi_albert_graph(n, m, seed=None):
    """Returns a random graph according to the Barabási–Albert preferential attachment model.

    Parameters:
    n (int): Number of nodes
    m (int): Number of edges to attach from a new node to existing nodes
    seed (int, optional): Seed for random number generator (default=None)

    Returns:
    G (Graph): A graph generated by the Barabási–Albert model
    """
    if m >= n:
        raise nx.NetworkXError("m must be less than or equal to n")

    if seed is not None:
        random.seed(seed)

    # Initialize the graph with m nodes and no edges
    G = nx.empty_graph(m)

    # List of nodes to which new nodes will be connected
    targets = list(range(m))

    # List of existing nodes, with nodes repeated once for each adjacent edge
    repeated_nodes = []

    # Start adding the other n-m nodes.
    source = m
    while source < n:
        # Add edges to m nodes from the source.
        G.add_edges_from(zip([source] * m, targets))
        # Add one node to the list for each new edge just created.
        repeated_nodes.extend(targets)
        # And the new node "source" has m edges to add to the list.
        repeated_nodes.extend([source] * m)

        # Now choose m unique nodes from the existing nodes
        # Pick uniformly from repeated_nodes (preferential attachment)
        targets = random.sample(repeated_nodes, m)
        source += 1

    return G

